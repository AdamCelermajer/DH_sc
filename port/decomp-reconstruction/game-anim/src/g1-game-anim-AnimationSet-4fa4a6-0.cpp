// 0x3649e0 _ZN12AnimationSet19_FindCacheCandidateEv
// Walks the entries in key order, as the original walks its tree in order. An entry with a positive use count
// (Animation +0x24, m_useCount) is skipped. Among the others the lowest counter (+0x2c, unk_2c, compared as
// unsigned) wins, and an equal counter goes to the entry with the older last-use stamp (+0x28, m_lastUseTime).
// The comparison values are seeded from the first entry, as the original seeds them from the leftmost node, so
// that entry is chosen only by a later comparison. When nothing is chosen the result is the key of the first
// entry that is not in use, and -1 when every entry is in use or the set is empty.
int AnimationSet::_FindCacheCandidate() {
    int candidate = -1;
    int fallback = -1;
    if (m_animations.empty()) {
        return fallback;
    }
    auto node = m_animations.begin();
    std::uint32_t bestCounter = static_cast<std::uint32_t>(node->second.unk_2c);
    std::uint32_t bestStamp = node->second.m_lastUseTime;
    for (; node != m_animations.end(); ++node) {
        const Animation& entry = node->second;
        if (entry.m_useCount > 0) {
            continue;
        }
        if (fallback == -1) {
            fallback = node->first;
        }
        const std::uint32_t counter = static_cast<std::uint32_t>(entry.unk_2c);
        if (counter < bestCounter) {
            bestCounter = counter;
            bestStamp = entry.m_lastUseTime;
            candidate = node->first;
        } else if (counter == bestCounter && bestStamp > entry.m_lastUseTime) {
            bestStamp = entry.m_lastUseTime;
            candidate = node->first;
        }
    }
    return candidate != -1 ? candidate : fallback;
}

