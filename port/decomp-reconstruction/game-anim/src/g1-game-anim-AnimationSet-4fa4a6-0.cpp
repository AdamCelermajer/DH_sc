// 0x364bf4 _ZN12AnimationSet22GetAnimationBySetIndexEi
// Scans the entries in key order for the first one whose set index (Animation +0x20, unk_20 in dh2/Animation.hpp)
// equals setIndex. A hit stamps that entry's last-use time (+0x28) from glitch::os::Timer::getRealTime() and
// returns it. A miss returns the invalid entry.
Animation* AnimationSet::GetAnimationBySetIndex(int setIndex) {
    for (auto node = m_animations.begin(); node != m_animations.end(); ++node) {
        if (node->second.unk_20 == setIndex) {
            node->second.m_lastUseTime = glitch::os::Timer::getRealTime();
            return &node->second;
        }
    }
    return &s_invalidAnim;
}

