const MenuArt* original_stat_page_art(StatPage,bool has_stat_points);
const MenuArt* original_stat_element_art(StatPage,unsigned hand,int element);
// Authored hit rectangle (480x320 px) of each page icon button (sprite 278 bounds under CharacterSheetNew/buttons).
