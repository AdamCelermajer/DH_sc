// P16 QUESTUI: Tab::quest is the Quest Log tab (btnQuestLogTab, 5th tab).
// P16 map: Tab::map is the Map page (menu_MapSheet, MenuCharMenu_Map, 6th tab). Its controls
// (Show legend / Reset zoom) are accepted only while the Map tab is selected.
enum class Tab { stats,equipment,skills,faery,quest,map };
// B111: the Statistics tab owns five sub-pages (SWF menu_CharacterSheetStats/Defense/Offense/Magic/Recovery). The five
// icons of CharacterSheetNew's `buttons` clip (btnStatisticsTab/Defence/Offense/Magic/Recovery) switch between them.
enum class StatPage { stats,defense,offense,magic,recovery };
// Action values are only ever appended (they travel through SemanticInput as menu_item ids).
enum class Action { none,stats,equipment,skills,faery,quest,map,map_legend,map_reset_zoom,close,
                    stat_page_stats,stat_page_defense,stat_page_offense,stat_page_magic,stat_page_recovery };
constexpr StatPage stat_page_of(Action a) noexcept {
    return a==Action::stat_page_defense?StatPage::defense:a==Action::stat_page_offense?StatPage::offense:
           a==Action::stat_page_magic?StatPage::magic:a==Action::stat_page_recovery?StatPage::recovery:StatPage::stats;
}
constexpr bool is_stat_page_action(Action a) noexcept {return a>=Action::stat_page_stats&&a<=Action::stat_page_recovery;}
constexpr Action stat_page_action(StatPage p) noexcept {
    return p==StatPage::defense?Action::stat_page_defense:p==StatPage::offense?Action::stat_page_offense:
           p==StatPage::magic?Action::stat_page_magic:p==StatPage::recovery?Action::stat_page_recovery:Action::stat_page_stats;
}
struct MenuTextField {
    std::string path;std::uint32_t character_id=0,font_id=0;float source_height=0;
    std::array<float,4> bounds{};std::array<std::uint8_t,4> rgba{};unsigned align=0;
    // Actual field transform/local RECT and paragraph spacing, in source
    // pixels. Root may retain source typography rather than flattening bounds.
    std::array<float,6> matrix{1,0,0,1,0,0};
    std::array<float,4> local_bounds{};
    std::array<float,3> margins{};float leading=0;
};
struct MenuSolidBatch {
    HudGeometryBatch geometry;std::array<float,4> rgba{1,1,1,1};
    // Insert after this actual bitmap role to retain source display-list order.
    std::string after_bitmap_role;
};
struct MenuArt { std::vector<HudGeometryBatch> batches;std::vector<MenuTextField> text_fields;std::vector<MenuSolidBatch> solids; };
struct MenuHitZone { Action action=Action::none;std::string path;std::vector<HudGeometryVertex> triangles; };
const MenuArt& original_menu_art(Tab,bool has_stat_points=true);
// B111: CharacterSheetNew chrome + the selected Statistics sub-page (Defense/Offense/Magic/Recovery); nullptr for
