"""B111: export the four non-default Statistics sub-pages (Defense/Offense/Magic/Recovery) of the original character menu.

Reuses export_art.py's SWF parsing + walk() verbatim (it executes the module up to its placement helpers), so the
contours/text fields/solids are produced by exactly the same code as the existing art0 (Stats page). Output:
stat_pages_art.cpp (generated; `--check` compares the regenerated Stats variant with the existing art0 in original_art.cpp).
Run from the repository root:  py -3 -I port/windows-foundation/features/character_menu/export_stat_pages.py [--check]
"""
import sys,json
from pathlib import Path
HERE=Path(__file__).resolve().parent
src=(HERE/'export_art.py').read_text(encoding='utf-8')
src=src[:src.index("tabs=placement('menu_CharacterMenu')")]
src=src.replace("ROOT=Path(__file__).resolve().parents[4]","ROOT=Path(__file__).resolve().parents[4]").replace("__file__",repr(str(HERE/'export_art.py')))
g={'__name__':'export_art_reuse'};exec(compile(src,'export_art.py','exec'),g)
swf=g['swf'];sprites=g['sprites'];walk=g['walk'];placement=g['placement'];source_solids=g['source_solids']
# The shared shape reader now parses solid-fill shapes as textured art. The committed art0 draws the btn_train_* glow
# overlays (shapes 311/315) as source solids instead (single solid fill, authored rgba), so reproduce that exactly.
for code,tag in swf.tags(g['data'],g['at'],len(g['data'])):
    if code in(2,22,32):
        ident=swf.struct.unpack_from('<H',tag)[0] if hasattr(swf,'struct') else __import__('struct').unpack_from('<H',tag)[0]
        if ident in(311,315):
            g['hit_color_bytes']=4 if code==32 else 3
            g['hit_shapes'][ident]=g['parse_solid_hit'](code,tag);g['shapes'].pop(ident,None)
def numbers(v):return '{'+','.join(swf.cpp_number(float(n)) for n in v)+'}'
def emit_block(lines,art_name,art,text,first_solid):
    lines.append(f'static const MenuArt {art_name}{{')
    lines.append('{'+','.join('{'+json.dumps(path)+','+str(char)+',{'+','.join(numbers(v) for v in verts)+'}}' for path,char,verts in art if verts)+'},')
    lines.append('{'+','.join('{'+json.dumps(path)+','+str(char)+','+str(rec['font'])+','+swf.cpp_number(rec['height_twips']/20)+','+numbers(bounds)+',{'+','.join(str(c) for c in rec['rgba'])+'},'+str(rec['layout'].get('align',0))+','+numbers(m[:4]+[m[4]/20,m[5]/20])+','+numbers([v/20 for v in rec['bounds_twips']])+','+numbers([rec['layout'].get(key,0)/20 for key in('left_margin','right_margin','indent')])+','+swf.cpp_number(rec['layout'].get('leading',0)/20)+'}' for path,char,rec,bounds,m in text)+'}')
    lines[-1]+=','
    lines.append('{'+','.join('{{'+json.dumps(role)+','+str(ident)+',{'+','.join(numbers(v) for v in verts)+'}},'+numbers(color)+','+json.dumps(after)+'}' for role,ident,verts,color,after in source_solids[first_solid:])+'}')
    lines.append('};')
tabs=placement('menu_CharacterMenu');sheet=placement('menu_CharacterSheetNew')
pages=[('Stats','menu_CharacterSheetStats'),('Defense','menu_CharacterSheetDefense'),('Offense','menu_CharacterSheetOffense'),
       ('Magic','menu_CharacterSheetMagic'),('Recovery','menu_CharacterSheetRecovery')]
lines=['// Generated by export_stat_pages.py (B111): original dqcharmenu CharacterSheetNew + the selected Statistics sub-page.',
       '// Same walk()/emission as original_art.cpp art0; the Stats page is NOT repeated here (art0 / art0_no_points).',
       '#include "character_menu.hpp"','namespace dh::foundation::character_menu {']
check={}
for name,placed in pages:
    for points,suffix in((True,''),(False,'_no_points')):
        art=[];text=[];first=len(source_solids)
        for p in (tabs,sheet,placement(placed)):
            walk(p['character'],p['matrix'],p.get('name','panel'),art,text,0,'stats',points)
        block=[];emit_block(block,'art_'+name.lower()+suffix,art,text,first);check[(name,suffix)]=block
        if name!='Stats':lines+=block
# Icon hit zones: the clickable clip is the whole button sprite (btnXTab, sprite 278): background + CharIcon.
btns=swf.placed_path(sprites[sheet['character']],'buttons')
bm=swf.multiply(sheet['matrix'],btns['matrix']);zones=[]
for btn,action in (('btnStatisticsTab','stats'),('btnDefenceTab','defense'),('btnOffenseTab','offense'),('btnMagicTab','magic'),('btnRecoveryTab','recovery')):
    b=swf.placed_path(sprites[btns['character']],btn);m=swf.multiply(bm,b['matrix']);art=[];text=[]
    walk(b['character'],m,btn,art,text,0,'stats',True)
    verts=[v for _,_,vs in art for v in vs]
    xs=[v[0] for v in verts];ys=[v[1] for v in verts]
    print(btn,'bounds',round(min(xs),2),round(max(xs),2),round(min(ys),2),round(max(ys),2),file=sys.stderr)
    # axis-aligned bounding rectangle of the clip's shapes (Flash button hit area = clip bounds), one rectangle {x0,y0,x1,y1}
    x0,x1,y0,y1=min(xs),max(xs),min(ys),max(ys)
    zones.append('{StatPage::%s,%s}'%(action,','.join(swf.cpp_number(float(n)) for n in (x0,y0,x1,y1))))
lines.append('const std::vector<StatPageHitZone>& original_stat_page_hit_zones(){static const std::vector<StatPageHitZone> zones{'+','.join(zones)+'};return zones;}')
sel=[]
for name,_ in pages[1:]:
    sel.append('case StatPage::%s:return points?&art_%s:&art_%s_no_points;'%(name.lower(),name.lower(),name.lower()))
lines.append('const MenuArt* original_stat_page_art(StatPage page,bool points){switch(page){'+''.join(sel)+'default:return nullptr;}}')
lines.append('}')
out=HERE/'stat_pages_art.cpp'
if '--check' in sys.argv:
    existing=(HERE/'original_art.cpp').read_text(encoding='utf-8')
    for suffix,real in (('','art0'),('_no_points','art0_no_points')):
        mine='\n'.join(check[('Stats',suffix)]).replace('art_stats'+suffix,real)
        print('Stats variant',suffix or 'points','reproduces art0:',mine in existing)
else:
    out.write_text('\n'.join(lines)+'\n',encoding='utf-8');print('wrote',out,out.stat().st_size)
if False:
    existing=(HERE/'original_art.cpp').read_text(encoding='utf-8').split('\n')
    mine=check[('Stats','')]
    for i in range(1,len(mine)):
        a=mine[i];b=existing[3+i] if True else ''
        if a!=b:
            n=next((k for k,(x,y) in enumerate(zip(a,b)) if x!=y),min(len(a),len(b)))
            print('line',i,'len',len(a),len(b),'first diff at',n,'\nmine:',a[max(0,n-150):n+150],'\norig:',b[max(0,n-150):n+150])
        else:print('line',i,'same')
