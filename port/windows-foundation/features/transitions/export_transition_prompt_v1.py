"""Export B113 upper destination button from the authored dqhud display list.
Uses the existing checked HUD panel decoder; does not export the separate World map action.
"""
from pathlib import Path
import json
import runpy

HERE = Path(__file__).resolve().parent
panel = runpy.run_path(str(HERE.parent / 'hud_panels/export_hud_panels_v1.py'))
swf = panel['Swf'](panel['SOURCE'])
root = swf.named(swf.root, 'LocationsMenu')
frame = swf.frame_of(root['character'], 'Idle')
button = swf.named(swf.sprites[root['character']][frame], 'btn_LocTravel')
matrix = panel['compose'](root['matrix'], button['matrix'])
idle = swf.frame_of(button['character'], 'idle')
batches = panel['batches'](swf, button['character'], idle, matrix, 'LocationsMenu/btn_LocTravel')
texts = []
panel['edit_slots'](swf, button['character'], idle, matrix, texts)
assert len(texts) == 1 and texts[0]['name'] == 'text' and texts[0]['font'] == 7
assert texts[0]['height'] == 10 and texts[0]['align'] == 2
text = texts[0]
nums = panel['cpp_num']
x0,y0,x1,y1 = text['rect']
# [E] is an explicit PC input adaptation beside the original button, outside its destination text box.
source = '// Generated by export_transition_prompt_v1.py from dqhud_droid.swf '+swf.raw_sha256+'\n'
source += 'namespace {\nconst std::vector<generic_skills::PcGameplayHudArtBatchV1> travelButtonArt{'+panel['cpp_batches'](batches)+'};\n'
source += 'const PromptText travelDestination{'+','.join(nums(v) for v in (x0,y0,x1-x0,y1-y0))+',"",{255,255,255,255},10.0f,2};\n}\n'
(HERE/'transition_prompt_art_v1.inc').write_text(source,encoding='utf-8')
receipt = {'source_sha256':swf.raw_sha256, 'path':'LocationsMenu/btn_LocTravel/text', 'root':root, 'button':button, 'idle_frame':idle,'texts':texts,'shape_ids':[b['shape'] for b in batches], 'art_bounds':[min(v[0] for b in batches for v in b['triangles']),min(v[1] for b in batches for v in b['triangles']),max(v[0] for b in batches for v in b['triangles']),max(v[1] for b in batches for v in b['triangles'])]}
(HERE/'transition_prompt_source_v1.json').write_text(json.dumps(receipt,indent=2)+'\n',encoding='utf-8')
print(json.dumps(receipt,indent=2))
