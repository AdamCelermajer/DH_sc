"""B110: export the menu_Merchant (sprite 251) chrome that the shared Details panel lacks:
title, BUY/SELL tabs (Idle/On), btn_Action (idle/disabled), btn_Back, MerchantErrorPopup (settled).
Reuses the character-menu walker (export_art.py is exec'd up to its panel loop; it never writes).
Usage: py -3 -I export_merchant_art.py  (writes merchant_art.cpp next to this file)"""
import sys,json
from pathlib import Path
here=Path(__file__).resolve()
src_path=here.parents[1]/'character_menu'/'export_art.py'
text=src_path.read_text(encoding='utf-8')
cut=text.index('def placement(name)')
ns={'__file__':str(src_path),'__name__':'export_art_walk'}
sys.argv=[sys.argv[0]]
exec(compile(text[:cut],str(src_path),'exec'),ns)
swf=ns['swf'];sprites=ns['sprites'];labels=ns['labels'];walk=ns['walk'];root=ns['root'];hit_shapes=ns['hit_shapes']
source_solids=ns['source_solids'];vertices=ns['vertices']
merchant=swf.placed_path(root,'menu_Merchant')
mm=merchant['matrix']
def child(name):
    p=swf.placed_path(sprites[merchant['character']],name);return p,swf.multiply(mm,p['matrix'])
def numbers(v):return '{'+','.join(swf.cpp_number(float(n)) for n in v)+'}'
lines=['// Generated by export_merchant_art.py from the original dqcharmenu_droid.swf menu_Merchant (sprite 251). Do not edit.',
 '#include "merchant_art.hpp"','namespace dh::foundation::merchant {']
def block(name,art,text_fields,solids_from):
    lines.append(f'static const character_menu::MenuArt {name}{{')
    lines.append('{'+','.join('{'+json.dumps(path)+','+str(char)+',{'+','.join(numbers(v) for v in verts)+'}}' for path,char,verts in art if verts)+'},')
    lines.append('{'+','.join('{'+json.dumps(path)+','+str(char)+','+str(rec['font'])+','+swf.cpp_number(rec['height_twips']/20)+','+numbers(bounds)+',{'+','.join(str(c) for c in rec['rgba'])+'},'+str(rec['layout'].get('align',0))+','+numbers(m[:4]+[m[4]/20,m[5]/20])+','+numbers([v/20 for v in rec['bounds_twips']])+','+numbers([rec['layout'].get(key,0)/20 for key in('left_margin','right_margin','indent')])+','+swf.cpp_number(rec['layout'].get('leading',0)/20)+'}' for path,char,rec,bounds,m in text_fields)+'},')
    lines.append('{'+','.join('{{'+json.dumps(role)+','+str(ident)+',{'+','.join(numbers(v) for v in verts)+'}},'+numbers(color)+','+json.dumps(after)+'}' for role,ident,verts,color,after in source_solids[solids_from:])+'}')
    lines.append('};')
def export(name,child_name,sprite=None,frame=None):
    p,m=child(child_name);art=[];tx=[];first=len(source_solids)
    saved=None
    if sprite is not None:
        saved=sprites[sprite];sprites[sprite]=[saved[frame]]
    walk(p['character'],m,'menu_Merchant/'+child_name,art,tx,0,'equipment',True)
    if saved is not None:sprites[sprite]=saved
    block(name,art,tx,first);return p,m
export('title_art','MENU_title')
export('tab_buy_idle','btn_Buy',227,0);export('tab_buy_on','btn_Buy',227,2)
export('tab_sell_idle','btn_Sell',227,0);export('tab_sell_on','btn_Sell',227,2)
export('action_idle','btn_Action',202,0);export('action_disabled','btn_Action',202,labels[202]['disabled'])
export('potions_idle','btn_BuyPotions',215,0)
export('back_art','btn_Back',223,0)
# settled error popup: hide label frame - 1 is the fully shown state
export('error_art','MerchantErrorPopup',250,labels[250]['hide']-1)
def hit(child_name,sprite):
    p,m=child(child_name);hp=swf.placed_path(sprites[sprite],'hitzone');hm=swf.multiply(m,hp['matrix'])
    return 'std::vector<float>'+numbers([c for v in vertices(hit_shapes[82],hm) for c in v[:2]])
def hit_back():
    p,m=child('btn_Back');art=[];tx=[]
    walk(p['character'],m,'btn_Back',art,tx,0,'equipment',True)
    xs=[v[0] for _,_,vs in art for v in vs];ys=[v[1] for _,_,vs in art for v in vs]
    x0,x1,y0,y1=min(xs),max(xs),min(ys),max(ys)
    return 'std::vector<float>'+numbers([x0,y0,x1,y0,x1,y1,x0,y0,x1,y1,x0,y1])
lines.append('const MerchantArt& merchant_art(){static const MerchantArt art{title_art,tab_buy_idle,tab_buy_on,tab_sell_idle,tab_sell_on,action_idle,action_disabled,potions_idle,back_art,error_art,')
lines.append('{{'+hit('btn_Buy',227)+','+hit('btn_Sell',227)+','+hit('btn_Action',202)+','+hit('btn_BuyPotions',215)+','+hit_back()+'}}};return art;}')
lines.append('}')
(here.parent/'merchant_art.cpp').write_text('\n'.join(lines)+'\n',encoding='utf-8')
print('ok',len(lines))
