"""Original HUD status line (HUDelements.itemname_text, sprite 166) timeline and placement.

Source: port/android-native/app/src/main/assets/original-cache/data/menus/dqhud_droid.swf. Uses the checked tag
decoder of tools/export_hud_geometry.py. Resolves menu_HUD_0 -> HUDelements -> itemname_text, the 48-frame
timeline of sprite 166 (container placement: matrix + colour-transform alpha per frame), the container's
infotext field (sprite 165 -> EditText 164) and the SWF frame rate, and fails on anything unexpected.

Output: status_message_timeline_v1.inc (generated, do not hand-edit).
"""
from __future__ import annotations

import importlib.util
import struct
import zlib
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = Path(__file__).resolve().parents[4]
SOURCE = ROOT / "port/android-native/app/src/main/assets/original-cache/data/menus/dqhud_droid.swf"
OUTPUT = HERE / "status_message_timeline_v1.inc"
spec = importlib.util.spec_from_file_location("hudgeo", ROOT / "port/windows-foundation/tools/export_hud_geometry.py")
hudgeo = importlib.util.module_from_spec(spec)
spec.loader.exec_module(hudgeo)


def fl(v):
    text = f"{v:.9g}"
    return text + (".0f" if all(c in "-0123456789" for c in text) else "f")


def main():
    raw = SOURCE.read_bytes()
    data = raw[:8] + zlib.decompress(raw[8:]) if raw[:3] == b"CWS" else raw
    stage, at = hudgeo.rect(data, 8)
    if stage != [0, 9600, 0, 6400]:
        raise ValueError("Unexpected original HUD stage")
    fps256, frames = struct.unpack_from("<HH", data, at)
    if fps256 != 30 * 256:
        raise ValueError("Unexpected HUD frame rate")
    at += 4
    sprites, edits, labels = {}, {}, {}
    for code, tag in hudgeo.tags(data, at, len(data)):
        if code == 39:
            char, count = struct.unpack_from("<HH", tag)
            sprites[char] = hudgeo.parse_timeline(tag, 4)
            if len(sprites[char]) != count:
                raise ValueError("Sprite frame count mismatch")
            labels[char], frame = {}, 0
            for sub_code, sub in hudgeo.tags(tag, 4, len(tag)):
                if sub_code == 43:
                    labels[char][sub.split(b"\0")[0].decode()] = frame
                elif sub_code == 1:
                    frame += 1
        elif code == 37:
            record = hudgeo.parse_edit_text(tag)
            edits[record["character"]] = record
    root = hudgeo.parse_timeline(data, at)
    menu = hudgeo.placed_path(root, "menu_HUD_0")
    elements = hudgeo.placed_path(sprites[menu["character"]], "HUDelements")
    item = hudgeo.placed_path(sprites[elements["character"]], "itemname_text")
    if item["character"] != 166 or len(sprites[166]) != 48 or labels[166].get("scroll") != 8:
        raise ValueError("Original status sprite differs")
    chain = hudgeo.multiply(hudgeo.multiply(menu["matrix"], elements["matrix"]), item["matrix"])
    container = [hudgeo.placed_path([frame], "container") for frame in sprites[166]]
    if any(p["character"] != 165 for p in container):
        raise ValueError("Status container sprite differs")
    info = hudgeo.placed_path(sprites[165], "infotext")
    field = edits[info["character"]]
    if field["font"] != 7 or field["layout"]["align"] != 2:
        raise ValueError("Status text field differs")
    out = ["// Generated by export_status_message_v1.py from dqhud_droid.swf; do not hand-edit.",
           f"// SWF frame rate {fps256 // 256} fps; label scroll = frame {labels[166]['scroll']}; frames {len(container)}.",
           f"// menu_HUD_0 * HUDelements * itemname_text, twips: {', '.join(f'{v:.6g}' for v in chain)}",
           f"constexpr float status_root_matrix[6]{{{', '.join(fl(v) for v in chain)}}};",
           f"// infotext placement inside the container (twips) and its EditText: bounds {field['bounds_twips']}, "
           f"height {field['height_twips']} twips, font {field['font']}, align {field['layout']['align']}",
           f"constexpr float status_info_matrix[6]{{{', '.join(fl(v) for v in info['matrix'])}}};",
           f"constexpr float status_field_bounds_twips[4]{{{', '.join(str(v) + '.f' for v in field['bounds_twips'])}}};",
           f"constexpr float status_font_height_twips = {field['height_twips']}.f;",
           "// Per frame: container colour-transform alpha multiplier, matrix d (Y scale), ty and tx in twips.",
           "constexpr StatusFrame status_frames[48]{"]
    for p in container:
        mult = p["color"][0][3]
        m = p["matrix"]
        if m[1] or m[2] or m[0] != 1.0:
            raise ValueError("Unexpected rotated/X-scaled status frame")
        out.append(f" {{{fl(mult)},{fl(m[3])},{fl(m[5])},{fl(m[4])}}},")
    out.append("};")
    out.append(f"constexpr int status_scroll_frame = {labels[166]['scroll']};")
    out.append(f"constexpr float status_frames_per_second = {fps256 // 256}.f;")
    OUTPUT.write_text("\n".join(out) + "\n")
    print("wrote", OUTPUT)


if __name__ == "__main__":
    main()
