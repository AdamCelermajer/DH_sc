RuleDistributionCatalogV1 enumerate_source_rule_distributions_v1(
    std::size_t open_exit_count, std::size_t child_rule_count) {
  RuleDistributionCatalogV1 result;
  if (open_exit_count > 5 || child_rule_count > 5) {
    result.status = RuleDistributionStatusV1::unsupported_domain;
    return result;
  }

  if (open_exit_count == 0 || child_rule_count == 0) {
    result.status = RuleDistributionStatusV1::bypass_success;
    return result;
  }

  for (const auto& row : kRows) {
    if (row.open_exits != open_exit_count || row.child_rules != child_rule_count) continue;
    if (row.hex_records.size() != static_cast<std::size_t>(row.record_count) * 12) {
      result.status = RuleDistributionStatusV1::unsupported_domain;
      return result;
    }

    result.status = RuleDistributionStatusV1::ready;
    result.records.reserve(row.record_count);
    for (std::size_t record_index = 0; record_index < row.record_count; ++record_index) {
      SourceRuleDistributionRecordV1 record;
      const std::size_t record_offset = record_index * 12;
      for (std::size_t byte_index = 0; byte_index < record.bytes.size(); ++byte_index) {
        const std::size_t offset = record_offset + byte_index * 2;
        record.bytes[byte_index] = static_cast<std::uint8_t>(
            (hex_nibble(row.hex_records[offset]) << 4) |
            hex_nibble(row.hex_records[offset + 1]));
      }
      result.records.push_back(record);
    }
    return result;
  }

  result.status = RuleDistributionStatusV1::unsupported_shape;
  return result;
}

bool shuffle_source_rule_distributions_v1(RuleDistributionCatalogV1& catalog,
                                          RandomGeneratorV1& random) {
  return source_shuffle(catalog.records, random);
}

