struct Range{std::uintptr_t first,end;};
bool range(const void* p,std::size_t size,std::size_t alignment,Range& out) {
    const auto at=reinterpret_cast<std::uintptr_t>(p);
    if(!p || at%alignment || at>UINTPTR_MAX-size)return false;
    out={at,at+size};return true;
}
bool overlap(Range a,Range b){return a.first<b.end && b.first<a.end;}
Status entries(const State& state,const Services& services,Result* out,const Binding* rows,std::size_t count) {
    for(std::size_t i=0;i<count;++i) {
        if(!services.bind)return Status::service_unavailable;
        const auto& row=rows[i];const auto userdata=row.context==Context::character?state.character:0;
        ++out->calls;
        try {if(services.bind(services.context,state.binder,&row,userdata))return Status::service_failed;}
        catch(...){return Status::service_failed;}
        if(row.kind==Kind::function)++out->functions_bound;else ++out->methods_bound;
    }
    return Status::complete;
}
Status run(const State* state,const Services* services,Result* out,bool character) {
    Range controls[3];
    if(!range(state,sizeof(*state),alignof(State),controls[0]) ||
       !range(services,sizeof(*services),alignof(Services),controls[1]) ||
       !range(out,sizeof(*out),alignof(Result),controls[2]))return Status::invalid_argument;
    for(unsigned i=0;i<3;++i)for(unsigned j=0;j<i;++j)if(overlap(controls[i],controls[j]))return Status::invalid_argument;
    if(!state->character || !state->binder)return Status::invalid_argument;
    const auto captured=*state;const auto bound=*services;*out={};
    auto status=entries(captured,bound,out,base,86);
    if(status!=Status::complete)return status;
    return character?entries(captured,bound,out,own,179):Status::complete;
}
